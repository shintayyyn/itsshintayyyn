#!/usr/bin/env node
/* ==========================================================================
   SEO / AI-discoverability build
   Run after editing assets/js/data.js:   node tools/build-seo.mjs

   Writes, from your content:
   • crawler-readable HTML (<div id="ssr">) into every page — search engines and
     AI crawlers that don't run JavaScript can read the full site; the live page
     removes it on load, so visitors never see it twice
   • <title>, description, canonical, Open Graph / Twitter cards, JSON-LD (schema.org)
   • one real page per project / blog post: project-<slug>.html, blog-<slug>.html
   • sitemap.xml · robots.txt (search + AI crawlers allowed) · llms.txt
   ========================================================================== */
import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const read = (f) => fs.readFileSync(path.join(ROOT, f), 'utf8');
const write = (f, s) => { fs.writeFileSync(path.join(ROOT, f), s); console.log('  wrote', f); };

// load the site content exactly as the browser does
const ctx = { window: {} }; vm.createContext(ctx);
vm.runInContext(read('assets/js/data.js'), ctx);
const { SITE: S, PROJECTS: P, POSTS: B, TESTIMONIALS: T = [], ABOUT: A = {}, EDUCATION: E = [] } = ctx.window;

const BASE = (S.siteUrl || 'https://example.com').replace(/\/+$/, '');
const url = (p = '') => BASE + '/' + p.replace(/^\//, '').replace(/^index\.html$/, '');
const esc = (s = '') => String(s).replace(/[&<>"']/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[c]));
const FULL = S.fullName || S.name, ROLE = S.role || 'Product Designer & Creative Developer';
const CITY = S.city || 'Cebu', COUNTRY = 'Philippines';
const OG_IMAGE = url('assets/img/og.png');
const socials = (S.socials || []).filter((s) => !/^https?:\/\/(www\.)?[a-z]+\.com\/?$/i.test(s.url));   // skip bare placeholder links
const projectHref = (p) => `project-${p.slug}.html`, postHref = (b) => `blog-${b.slug}.html`;
const today = new Date().toISOString().slice(0, 10);

/* ---------- schema.org ---------- */
const person = {
  '@type': 'Person', '@id': url('#person'), name: FULL, alternateName: S.name, jobTitle: ROLE, email: 'mailto:' + S.email, url: url(),
  image: url('assets/img/avatar.svg'),
  address: { '@type': 'PostalAddress', addressLocality: CITY, addressCountry: 'PH' },
  sameAs: socials.map((s) => s.url), knowsAbout: A.services || [],
};
const website = { '@type': 'WebSite', '@id': url('#website'), url: url(), name: `${S.name} — ${ROLE}`, author: { '@id': url('#person') }, inLanguage: 'en' };
const graph = (...nodes) => JSON.stringify({ '@context': 'https://schema.org', '@graph': [person, website, ...nodes] }, null, 0).replace(/</g, '\\u003c');
const crumbs = (items) => ({ '@type': 'BreadcrumbList', itemListElement: items.map(([name, u], i) => ({ '@type': 'ListItem', position: i + 1, name, item: url(u) })) });
const textOf = (it) => (it.blocks || []).filter((b) => b.type === 'text').flatMap((b) => b.paras);

/* ---------- <head> block ---------- */
function head({ title, description, file, type = 'website', jsonld, extra = '' }) {
  return `<!-- SEO:START (generated by tools/build-seo.mjs — edit data.js, then re-run) -->
  <script>document.documentElement.classList.add('js')</script>
  <title>${esc(title)}</title>
  <meta name="description" content="${esc(description)}">
  <meta name="author" content="${esc(FULL)}">
  <meta name="robots" content="index, follow, max-image-preview:large, max-snippet:-1">
  <meta name="theme-color" content="#71b7f4">
  <link rel="canonical" href="${url(file)}">
  <link rel="sitemap" type="application/xml" href="sitemap.xml">
  <link rel="alternate" type="text/plain" title="LLM summary" href="llms.txt">
  <meta property="og:type" content="${type}">
  <meta property="og:site_name" content="${esc(S.name)}">
  <meta property="og:title" content="${esc(title)}">
  <meta property="og:description" content="${esc(description)}">
  <meta property="og:url" content="${url(file)}">
  <meta property="og:image" content="${OG_IMAGE}">
  <meta property="og:image:width" content="1200"><meta property="og:image:height" content="630">
  <meta property="og:locale" content="en_US">${extra}
  <meta name="twitter:card" content="summary_large_image">
  <meta name="twitter:title" content="${esc(title)}">
  <meta name="twitter:description" content="${esc(description)}">
  <meta name="twitter:image" content="${OG_IMAGE}">
  <script type="application/ld+json">${jsonld}</script>
  <!-- SEO:END -->`;
}

/* ---------- crawler-readable body (removed by the live page) ---------- */
const nav = `<nav aria-label="Site"><a href="index.html">Home</a> · <a href="projects.html">Projects</a> · <a href="blog.html">Blogs</a> · <a href="about.html">About</a> · <a href="mailto:${esc(S.email)}">Contact</a></nav>`;
const contact = `<section><h2>Contact</h2><p>Email: <a href="mailto:${esc(S.email)}">${esc(S.email)}</a> · Based in ${esc(CITY)}, ${COUNTRY}</p>
<ul>${socials.map((s) => `<li><a href="${esc(s.url)}" rel="me">${esc(s.label)}</a></li>`).join('')}</ul></section>`;
const projectItem = (p) => `<li><h3><a href="${projectHref(p)}">${esc(p.title)}</a></h3><p>${esc(p.description)}</p><p>${esc(p.role)} · ${esc(p.industry)} · ${esc(p.year)}</p></li>`;
const postItem = (b) => `<li><h3><a href="${postHref(b)}">${esc(b.title)}</a></h3><p><time datetime="${b.date}">${b.date}</time> — ${esc(b.description)}</p></li>`;
const ssr = (inner) => `<!-- SSR:START (generated; replaced by the live page) -->
<div id="ssr" class="ssr">
<header><p><a href="index.html">${esc(FULL)}</a> — ${esc(ROLE)}, ${esc(CITY)}</p>${nav}</header>
<main>${inner}</main>
<footer>${contact}<p>© ${new Date().getFullYear()} ${esc(FULL)}</p></footer>
</div>
<!-- SSR:END -->`;

/* ---------- inject into an HTML file ---------- */
function inject(html, headBlock, bodyBlock) {
  html = html.replace(/\s*<!-- SEO:START[\s\S]*?<!-- SEO:END -->/, '');
  html = html.replace(/\s*<!-- SSR:START[\s\S]*?<!-- SSR:END -->/, '');
  html = html.replace(/\s*<title>[\s\S]*?<\/title>/, '').replace(/\s*<meta name="description"[^>]*>/, '');
  html = html.replace(/(<meta name="viewport"[^>]*>)/, `$1\n  ${headBlock}`);
  html = html.replace(/(<body[^>]*>)/, `$1\n${bodyBlock}`);
  return html;
}

console.log(`Building SEO for ${BASE}`);
const pages = [];

/* home */
pages.push('index.html');
write('index.html', inject(read('index.html'),
  head({ title: `${FULL} — ${ROLE} in ${CITY}`, description: `${S.intro} Selected work: ${P.slice(0, 4).map((p) => p.title).join(', ')}.`, file: 'index.html', type: 'profile',
    jsonld: graph({ '@type': 'ProfilePage', url: url(), mainEntity: { '@id': url('#person') }, name: `${FULL} — Portfolio` }) }),
  ssr(`<h1>${esc(FULL)} — ${esc(ROLE)}</h1><p>${esc(S.eyebrow)} ${esc(S.heroLine)} ${esc(S.heroWords.join(', '))}.</p>
<section><p>${esc(S.intro)}</p><p><strong>${esc(S.manifesto)}</strong></p></section>
<section><h2>${esc(S.workHeading)}</h2><p>${esc(S.clients.join(', '))}</p><h2>Featured projects</h2><ul>${P.slice(0, 4).map(projectItem).join('')}</ul><p><a href="projects.html">All projects</a></p></section>
<section><h2>${esc(S.testimonialsHeading)}</h2>${T.map((t) => `<blockquote><p>${esc(t.quote)}</p><footer>— ${esc(t.name)}, ${esc(t.role)}</footer></blockquote>`).join('')}</section>
<section><h2>Latest blog posts</h2><ul>${B.slice(0, 3).map(postItem).join('')}</ul></section>
<section><h2>${esc(S.footerHead)}</h2><p>${esc(S.footerSub)}</p></section>`)));

/* projects */
pages.push('projects.html');
write('projects.html', inject(read('projects.html'),
  head({ title: `Projects — ${FULL}`, description: `${S.projectsSummary} ${P.map((p) => p.title).join(', ')}.`, file: 'projects.html',
    jsonld: graph({ '@type': 'CollectionPage', url: url('projects.html'), name: 'Projects', isPartOf: { '@id': url('#website') },
      mainEntity: { '@type': 'ItemList', itemListElement: P.map((p, i) => ({ '@type': 'ListItem', position: i + 1, url: url(projectHref(p)), name: p.title })) } },
      crumbs([['Home', ''], ['Projects', 'projects.html']])) }),
  ssr(`<h1>Projects</h1><p>${esc(S.projectsSummary)}</p><ul>${P.map(projectItem).join('')}</ul>`)));

/* blog */
pages.push('blog.html');
write('blog.html', inject(read('blog.html'),
  head({ title: `Blogs — ${FULL}`, description: `${S.writingSummary} ${B.map((b) => b.title).join(', ')}.`, file: 'blog.html',
    jsonld: graph({ '@type': 'Blog', url: url('blog.html'), name: `${S.name}'s blog`, author: { '@id': url('#person') },
      blogPost: B.map((b) => ({ '@type': 'BlogPosting', headline: b.title, url: url(postHref(b)), datePublished: b.date, description: b.description })) },
      crumbs([['Home', ''], ['Blogs', 'blog.html']])) }),
  ssr(`<h1>Blogs</h1><p>${esc(S.writingSummary)}</p><ul>${B.map(postItem).join('')}</ul>`)));

/* about */
pages.push('about.html');
write('about.html', inject(read('about.html'),
  head({ title: `About — ${FULL}`, description: `${A.heading || A.lead} Based in ${CITY}, ${COUNTRY}. ${(A.services || []).join(', ')}.`, file: 'about.html', type: 'profile',
    jsonld: graph({ '@type': 'AboutPage', url: url('about.html'), mainEntity: { '@id': url('#person') } }, crumbs([['Home', ''], ['About', 'about.html']])) }),
  ssr(`<h1>About ${esc(FULL)}</h1><p>${esc(A.heading || A.lead)}</p>${(A.bio || []).map((p) => `<p>${esc(p.replace(/<[^>]+>/g, ''))}</p>`).join('')}
<section><h2>Professional experience</h2>${(A.jobs || []).map((j) => `<h3>${esc(j.name)} — ${esc(j.role)}</h3><p>${esc(j.date)}</p>${j.summary ? `<p>${esc(j.summary)}</p>` : ''}<ul>${(j.bullets || []).map((b) => `<li>${esc(b)}</li>`).join('')}</ul>`).join('')}</section>
${(A.intro || []).map((x) => `<section><h2>${esc(x.title)}</h2><p>${esc(x.body)}</p></section>`).join('')}
<section><h2>Education</h2><ol>${E.map((e) => `<li><strong>${esc(e.level)}</strong> — ${esc(e.school)}, ${esc(e.place)} (${esc(e.years)}). ${esc(e.note)}</li>`).join('')}</ol></section>
<section><h2>${esc(A.principlesTitle)}</h2>${(A.principles || []).map((x) => `<h3>${esc(x.title)}</h3><p>${esc(x.body)}</p>`).join('')}</section>
<section><h2>Experience</h2><ul>${(A.experience || []).map((x) => `<li>${esc(x.role)} — ${esc(x.org)} (${esc(x.years)})</li>`).join('')}</ul></section>
<section><h2>Services</h2><ul>${(A.services || []).map((x) => `<li>${esc(x)}</li>`).join('')}</ul></section>
<section><h2>${esc(A.engagementTitle)}</h2>${(A.engagements || []).map((x) => `<h3>${esc(x.title)}</h3><p>${esc(x.body)}</p>`).join('')}</section>
<section><h2>Recent projects</h2><ul>${P.slice(0, 4).map(projectItem).join('')}</ul></section>`)));

/* one page per project / post, from the detail template */
const detailTpl = read('detail.html');
function detailPage(it, kind) {
  const isPost = kind === 'post', file = isPost ? postHref(it) : projectHref(it);
  const title = `${it.title} — ${isPost ? 'Blog' : 'Project'} by ${FULL}`;
  const body = textOf(it);
  const node = isPost
    ? { '@type': 'BlogPosting', headline: it.title, description: it.description, datePublished: it.date, dateModified: it.date, author: { '@id': url('#person') }, url: url(file), mainEntityOfPage: url(file), keywords: (it.tags || []).join(', '), image: OG_IMAGE }
    : { '@type': 'CreativeWork', name: it.title, description: it.description, dateCreated: it.year, creator: { '@id': url('#person') }, url: url(file), keywords: (it.tags || []).join(', '), genre: it.industry, image: OG_IMAGE,
        ...(it.links && it.links[0] ? { sameAs: it.links.map((l) => l.url) } : {}) };
  let html = inject(detailTpl,
    head({ title, description: `${it.description} ${body[0] || ''}`.slice(0, 300), file, type: 'article', jsonld: graph(node, crumbs([['Home', ''], isPost ? ['Blogs', 'blog.html'] : ['Projects', 'projects.html'], [it.title, file]])),
      extra: isPost ? `\n  <meta property="article:published_time" content="${it.date}">\n  <meta property="article:author" content="${esc(FULL)}">` : '' }),
    ssr(`<article><h1>${esc(it.title)}</h1><p>${esc(it.description)}</p>
<dl>${isPost ? `<dt>Published</dt><dd><time datetime="${it.date}">${it.date}</time></dd>` : `<dt>Industry</dt><dd>${esc(it.industry)}</dd><dt>Role</dt><dd>${esc(it.role)}</dd><dt>Year</dt><dd>${esc(it.year)}</dd>`}<dt>Topics</dt><dd>${esc((it.tags || []).join(', '))}</dd></dl>
${body.map((p) => `<p>${esc(p)}</p>`).join('')}
${(it.links || []).map((l) => `<p><a href="${esc(l.url)}">${esc(l.label)}</a></p>`).join('')}
<p><a href="${isPost ? 'blog.html' : 'projects.html'}">← All ${isPost ? 'blog posts' : 'projects'}</a></p></article>`));
  html = html.replace(/<body class="lp" data-page="detail"[^>]*>/, `<body class="lp" data-page="detail" data-type="${kind}" data-slug="${it.slug}">`);
  write(file, html); pages.push(file);
}
P.forEach((p) => detailPage(p, 'project'));
B.forEach((b) => detailPage(b, 'post'));

/* detail.html itself: keep working, but point search engines at the pretty pages */
write('detail.html', inject(detailTpl, head({ title: `Project — ${FULL}`, description: S.projectsSummary, file: 'projects.html', jsonld: graph() }).replace('index, follow', 'noindex, follow'), ''));

/* sitemap · robots · llms.txt */
write('sitemap.xml', `<?xml version="1.0" encoding="UTF-8"?>
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
${pages.map((f) => `  <url><loc>${url(f)}</loc><lastmod>${today}</lastmod><changefreq>${f === 'index.html' ? 'weekly' : 'monthly'}</changefreq><priority>${f === 'index.html' ? '1.0' : /^(project|blog)-/.test(f) ? '0.7' : '0.8'}</priority></url>`).join('\n')}
</urlset>
`);
const bots = ['Googlebot', 'Bingbot', 'DuckDuckBot', 'Applebot', 'GPTBot', 'OAI-SearchBot', 'ChatGPT-User', 'ClaudeBot', 'Claude-User', 'Claude-SearchBot', 'anthropic-ai', 'PerplexityBot', 'Perplexity-User', 'Google-Extended', 'CCBot', 'Meta-ExternalAgent', 'Amazonbot', 'cohere-ai'];
write('robots.txt', `# Search engines and AI assistants are welcome to read and cite this portfolio.
User-agent: *
Allow: /

${bots.map((b) => `User-agent: ${b}\nAllow: /`).join('\n\n')}

Sitemap: ${url('sitemap.xml')}
`);
write('llms.txt', `# ${FULL}

> ${ROLE} based in ${CITY}, ${COUNTRY}. ${S.intro}

- Email: ${S.email}
${socials.map((s) => `- ${s.label}: ${s.url}`).join('\n')}
- Services: ${(A.services || []).join('; ')}

## Pages
- [Home](${url()}): portfolio overview, featured work and testimonials
- [Projects](${url('projects.html')}): all case studies
- [Blogs](${url('blog.html')}): writing on design, typography, motion and building products
- [About](${url('about.html')}): background, principles, experience and how to work together

## Projects
${P.map((p) => `- [${p.title}](${url(projectHref(p))}): ${p.description} (${p.role}, ${p.industry}, ${p.year})`).join('\n')}

## Blog posts
${B.map((b) => `- [${b.title}](${url(postHref(b))}): ${b.description} (${b.date})`).join('\n')}

## Testimonials
${T.map((t) => `- "${t.quote}" — ${t.name}, ${t.role}`).join('\n')}
`);
console.log(`Done — ${pages.length} pages. Remember: siteUrl in assets/js/data.js must be your live domain.`);
